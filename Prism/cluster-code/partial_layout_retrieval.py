@dataclass
class Paths:
    """Resolved project paths used by the partial retrieval script."""

    processed_root: Path
    outputs_root: Path
    layouts_dir: Path
    graphs_dir: Path
    snapshots_dir: Path
    index_dir: Path
    results_dir: Path
    previews_dir: Path


def resolve_paths(processed_root: Path, outputs_root: Path, dataset_root: Path) -> Paths:
    """Create all internal paths from the user-provided roots."""
    layouts_dir = processed_root / "layouts_json"
    graphs_dir = processed_root / "graphs_json"
    snapshots_dir = dataset_root / "Interface/static/Data/snapshot_train"

    return Paths(
        processed_root=processed_root,
        outputs_root=outputs_root,
        layouts_dir=layouts_dir,
        graphs_dir=graphs_dir,
        snapshots_dir=snapshots_dir,
        index_dir=processed_root / "partial_retrieval",
        results_dir=outputs_root / "results",
        previews_dir=outputs_root / "previews",
    )


def ensure_clean_dir(path: Path, clean: bool = False) -> None:
    """Create a directory, optionally deleting previous content."""
    if clean and path.exists():
        shutil.rmtree(path)

    path.mkdir(parents=True, exist_ok=True)


def load_json(path: Path) -> Dict[str, Any]:
    """Load one JSON file."""
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, data: Any) -> None:
    """Write a JSON file."""
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def write_csv(path: Path, rows: List[Dict[str, Any]]) -> None:
    """Write rows to a CSV file."""
    if not rows:
        path.write_text("", encoding="utf-8")
        return

    fieldnames = sorted({key for row in rows for key in row.keys()})
    preferred = [
        "query_id",
        "rank",
        "candidate_id",
        "retrieved_original",
        "compatibility_score",
        "room_coverage",
        "adjacency_coverage",
        "relation_coverage",
        "grid_coverage",
        "size_compatibility",
        "faiss_similarity",
    ]
    fieldnames = [field for field in preferred if field in fieldnames] + [
        field for field in fieldnames if field not in preferred
    ]

    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()

        for row in rows:
            writer.writerow(row)


def get_room_type_id(room: Dict[str, Any]) -> int:
    """Get the canonical room type id from a room object."""
    if "room_type_id" in room:
        return int(room["room_type_id"])

    if "raw_type_id" in room:
        return int(room["raw_type_id"])

    raise KeyError("Room is missing both 'room_type_id' and 'raw_type_id'.")


def get_room_type_name(room: Dict[str, Any]) -> str:
    """Get the room type name from a room object."""
    if "room_type_name" in room:
        return str(room["room_type_name"])

    room_type_id = get_room_type_id(room)
    return ROOM_TYPE_ID_TO_NAME.get(room_type_id, f"Unknown_{room_type_id}")


def polygon_points(room: Dict[str, Any]) -> Optional[List[List[float]]]:
    """Return polygon points if available and valid."""
    polygon = room.get("polygon")

    if not isinstance(polygon, list) or len(polygon) < 3:
        return None

    points = []
    for point in polygon:
        if isinstance(point, list) and len(point) >= 2:
            points.append([float(point[0]), float(point[1])])

    if len(points) < 3:
        return None

    return points


def room_centroid(room: Dict[str, Any]) -> Tuple[float, float]:
    """Return the room centroid."""
    cx, cy = room["centroid"]
    return float(cx), float(cy)


def layout_room_counts(layout: Dict[str, Any], room_ids: Optional[Set[int]] = None) -> Counter:
    """Count room types in a layout, optionally restricted to a subset of room ids."""
    counts = Counter()

    for room in layout["rooms"]:
        room_id = int(room["id"])

        if room_ids is not None and room_id not in room_ids:
            continue

        counts[get_room_type_id(room)] += 1

    return counts


def typed_adjacency_set(layout: Dict[str, Any], graph: Dict[str, Any], room_ids: Optional[Set[int]] = None) -> Set[Tuple[int, int]]:
    """
    Build an undirected typed adjacency set.

    Each item is:
        (min(room_type_a, room_type_b), max(room_type_a, room_type_b))

    This ignores exact node ids and focuses on semantic room-type adjacency.
    """
    rooms_by_id = {int(room["id"]): room for room in layout["rooms"]}
    output = set()

    for edge in graph["edges"]:
        source = int(edge["source"])
        target = int(edge["target"])

        if room_ids is not None and (source not in room_ids or target not in room_ids):
            continue

        if source not in rooms_by_id or target not in rooms_by_id:
            continue

        type_a = get_room_type_id(rooms_by_id[source])
        type_b = get_room_type_id(rooms_by_id[target])
        output.add(tuple(sorted((type_a, type_b))))

    return output


def typed_relation_set(layout: Dict[str, Any], graph: Dict[str, Any], room_ids: Optional[Set[int]] = None) -> Set[Tuple[int, int, int]]:
    """
    Build a directed typed relation set.

    Each item is:
        (source_room_type, target_room_type, relation_id)

    The relation follows the Graph2Plan convention: relation_id describes the
    source room relative to the target room.
    """
    rooms_by_id = {int(room["id"]): room for room in layout["rooms"]}
    output = set()

    for edge in graph["edges"]:
        source = int(edge["source"])
        target = int(edge["target"])

        if room_ids is not None and (source not in room_ids or target not in room_ids):
            continue

        if source not in rooms_by_id or target not in rooms_by_id:
            continue

        source_type = get_room_type_id(rooms_by_id[source])
        target_type = get_room_type_id(rooms_by_id[target])
        relation_id = int(edge["relation_id"])
        output.add((source_type, target_type, relation_id))

    return output


def grid_type_set(layout: Dict[str, Any], room_ids: Optional[Set[int]] = None) -> Set[Tuple[int, int, int]]:
    """
    Build a set of semantic grid constraints.

    Each item is:
        (room_type_id, grid_x, grid_y)

    This approximates where known room types are located in the 5x5 layout grid.
    """
    output = set()

    for room in layout["rooms"]:
        room_id = int(room["id"])

        if room_ids is not None and room_id not in room_ids:
            continue

        room_type_id = get_room_type_id(room)
        gx, gy = room.get("grid_location_5x5", [None, None])

        if gx is None or gy is None:
            continue

        output.add((room_type_id, int(gx), int(gy)))

    return output


def build_layout_feature(layout: Dict[str, Any], graph: Dict[str, Any], room_ids: Optional[Set[int]] = None) -> np.ndarray:
    """
    Build a compact feature vector used for FAISS preselection.

    For full layouts, room_ids is None.
    For partial queries, room_ids contains the visible/known rooms.

    The final re-ranking is performed by explicit compatibility metrics, so
    this vector only needs to provide a reasonable candidate pool.
    """
    rooms = [
        room
        for room in layout["rooms"]
        if room_ids is None or int(room["id"]) in room_ids
    ]

    edges = [
        edge
        for edge in graph["edges"]
        if room_ids is None or (
            int(edge["source"]) in room_ids and int(edge["target"]) in room_ids
        )
    ]

    features: List[float] = []

    # Basic size information.
    features.append(float(len(rooms)))
    features.append(float(len(edges)))

    # Room type counts and ratios.
    counts = Counter(get_room_type_id(room) for room in rooms)

    for room_type_id in ROOM_TYPE_IDS:
        features.append(float(counts.get(room_type_id, 0)))

    for room_type_id in ROOM_TYPE_IDS:
        features.append(float(counts.get(room_type_id, 0)) / max(1, len(rooms)))

    # Relation counts.
    relation_counts = Counter(int(edge["relation_id"]) for edge in edges)

    for relation_id in RELATION_IDS:
        features.append(float(relation_counts.get(relation_id, 0)))

    # Area statistics.
    areas = [float(room.get("area_ratio", 0.0)) for room in rooms]

    if areas:
        features.extend([
            float(np.mean(areas)),
            float(np.std(areas)),
            float(np.min(areas)),
            float(np.max(areas)),
        ])
    else:
        features.extend([0.0, 0.0, 0.0, 0.0])

    # Grid occupancy by room type.
    grid_counts = Counter()
    for room in rooms:
        gx, gy = room.get("grid_location_5x5", [0, 0])
        grid_counts[(get_room_type_id(room), int(gx), int(gy))] += 1

    # Compressed grid: one value per room type with average x/y location.
    for room_type_id in ROOM_TYPE_IDS:
        xs = []
        ys = []

        for room in rooms:
            if get_room_type_id(room) == room_type_id:
                gx, gy = room.get("grid_location_5x5", [0, 0])
                xs.append(float(gx))
                ys.append(float(gy))

        features.append(float(np.mean(xs)) / 4.0 if xs else 0.0)
        features.append(float(np.mean(ys)) / 4.0 if ys else 0.0)

    return np.array(features, dtype=np.float32)


def l2_normalize(x: np.ndarray) -> np.ndarray:
    """L2-normalize a 2D NumPy array row-wise."""
    norms = np.linalg.norm(x, axis=1, keepdims=True)
    norms = np.maximum(norms, 1e-12)
    return (x / norms).astype(np.float32)


def build_index(paths: Paths, max_items: Optional[int] = None) -> None:
    """Build the full-layout FAISS index used for candidate preselection."""
    ensure_clean_dir(paths.index_dir, clean=True)

    graph_paths = sorted(paths.graphs_dir.glob("*.json"))

    if max_items is not None:
        graph_paths = graph_paths[:max_items]

    ids: List[str] = []
    vectors: List[np.ndarray] = []

    print(f"Building partial retrieval index from {len(graph_paths)} graphs...")

    for i, graph_path in enumerate(graph_paths, start=1):
        layout_path = paths.layouts_dir / graph_path.name

        if not layout_path.exists():
            continue

        graph = load_json(graph_path)
        layout = load_json(layout_path)

        vector = build_layout_feature(layout, graph, room_ids=None)
        ids.append(graph["id"])
        vectors.append(vector)

        if i % 5000 == 0:
            print(f"  processed {i}/{len(graph_paths)}")

    if not vectors:
        raise RuntimeError("No vectors were generated for the partial retrieval index.")

    X_raw = np.vstack(vectors).astype(np.float32)
    X = l2_normalize(X_raw)

    index = faiss.IndexFlatIP(X.shape[1])
    index.add(X)

    faiss.write_index(index, str(paths.index_dir / "partial_full_layouts.index"))
    np.save(paths.index_dir / "partial_full_layout_features_raw.npy", X_raw)
    np.save(paths.index_dir / "partial_full_layout_features_normalized.npy", X)

    write_json(paths.index_dir / "partial_full_layout_ids.json", ids)

    metadata = {
        "num_items": len(ids),
        "feature_dim": int(X.shape[1]),
        "metric": "cosine_inner_product",
        "index_file": str(paths.index_dir / "partial_full_layouts.index"),
    }
    write_json(paths.index_dir / "partial_index_metadata.json", metadata)

    print(f"Saved partial retrieval index to: {paths.index_dir}")


def load_index(paths: Paths) -> Tuple[Any, np.ndarray, List[str]]:
    """Load the FAISS index, normalized features, and layout ids."""
    index_path = paths.index_dir / "partial_full_layouts.index"
    features_path = paths.index_dir / "partial_full_layout_features_normalized.npy"
    ids_path = paths.index_dir / "partial_full_layout_ids.json"

    if not index_path.exists() or not features_path.exists() or not ids_path.exists():
        raise FileNotFoundError(
            "Partial retrieval index is missing. Run with --build first."
        )

    index = faiss.read_index(str(index_path))
    X = np.load(features_path)

    with open(ids_path, "r", encoding="utf-8") as f:
        ids = json.load(f)

    return index, X, ids


def choose_visible_rooms(
    layout: Dict[str, Any],
    strategy: str,
    remove_ratio: float,
    remove_type: Optional[int],
    rng: random.Random,
) -> Tuple[Set[int], Set[int]]:
    """
    Choose visible and removed room ids for a partial query.

    Strategies:
      - random: remove a random percentage of rooms;
      - remove_type: remove all rooms of a given room type id;
      - remove_bedroom: remove one bedroom-like room if present;
      - remove_smallest: remove the smallest room;
      - remove_largest: remove the largest room.
    """
    rooms = layout["rooms"]
    all_ids = {int(room["id"]) for room in rooms}

    if len(all_ids) <= 1:
        return all_ids, set()

    removed: Set[int] = set()

    if strategy == "random":
        n_remove = max(1, int(round(len(all_ids) * remove_ratio)))
        n_remove = min(n_remove, len(all_ids) - 1)
        removed = set(rng.sample(sorted(all_ids), n_remove))

    elif strategy == "remove_type":
        if remove_type is None:
            raise ValueError("--remove-type is required when --mask-strategy remove_type is used.")

        removed = {
            int(room["id"])
            for room in rooms
            if get_room_type_id(room) == int(remove_type)
        }

        if not removed:
            # Fallback to random if the requested room type is absent.
            n_remove = max(1, int(round(len(all_ids) * remove_ratio)))
            n_remove = min(n_remove, len(all_ids) - 1)
            removed = set(rng.sample(sorted(all_ids), n_remove))

    elif strategy == "remove_bedroom":
        bedroom_ids = [
            int(room["id"])
            for room in rooms
            if get_room_type_id(room) in {1, 5, 6, 7, 8}
        ]

        if bedroom_ids:
            removed = {rng.choice(bedroom_ids)}
        else:
            removed = {rng.choice(sorted(all_ids))}

    elif strategy == "remove_smallest":
        room = min(rooms, key=lambda item: float(item.get("area_ratio", 0.0)))
        removed = {int(room["id"])}

    elif strategy == "remove_largest":
        room = max(rooms, key=lambda item: float(item.get("area_ratio", 0.0)))
        removed = {int(room["id"])}

    else:
        raise ValueError(f"Unsupported mask strategy: {strategy}")

    if len(removed) >= len(all_ids):
        removed = set(sorted(removed)[:-1])

    visible = all_ids - removed
    return visible, removed


def coverage_score(query_items: Set[Any], candidate_items: Set[Any]) -> float:
    """Return the fraction of query items covered by a candidate set."""
    if not query_items:
        return 1.0

    return len(query_items & candidate_items) / len(query_items)


def room_coverage_score(query_counts: Counter, candidate_counts: Counter) -> float:
    """
    Compute lower-bound room count compatibility.

    Partial query counts are interpreted as known required rooms. A complete
    candidate should contain at least those known room types.
    """
    total_required = sum(query_counts.values())

    if total_required == 0:
        return 1.0

    covered = 0
    for room_type_id, count in query_counts.items():
        covered += min(count, candidate_counts.get(room_type_id, 0))

    return covered / total_required


def size_compatibility_score(num_visible: int, num_candidate: int) -> float:
    """
    Score whether the candidate is a plausible completion of the partial query.

    A complete candidate must have at least as many rooms as the partial query.
    Extra rooms are allowed but penalized gradually.
    """
    if num_candidate < num_visible:
        return 0.0

    extra = num_candidate - num_visible
    return float(math.exp(-extra / 6.0))


def compute_candidate_compatibility(
    query_layout: Dict[str, Any],
    query_graph: Dict[str, Any],
    candidate_layout: Dict[str, Any],
    candidate_graph: Dict[str, Any],
    visible_room_ids: Set[int],
    faiss_similarity: float,
) -> Dict[str, float]:
    """Compute explicit compatibility metrics between a partial query and a full candidate."""
    query_counts = layout_room_counts(query_layout, visible_room_ids)
    candidate_counts = layout_room_counts(candidate_layout, None)

    query_adj = typed_adjacency_set(query_layout, query_graph, visible_room_ids)
    candidate_adj = typed_adjacency_set(candidate_layout, candidate_graph, None)

    query_rel = typed_relation_set(query_layout, query_graph, visible_room_ids)
    candidate_rel = typed_relation_set(candidate_layout, candidate_graph, None)

    query_grid = grid_type_set(query_layout, visible_room_ids)
    candidate_grid = grid_type_set(candidate_layout, None)

    room_score = room_coverage_score(query_counts, candidate_counts)
    adjacency_score = coverage_score(query_adj, candidate_adj)
    relation_score = coverage_score(query_rel, candidate_rel)
    grid_score = coverage_score(query_grid, candidate_grid)
    size_score = size_compatibility_score(len(visible_room_ids), len(candidate_layout["rooms"]))

    # Compatibility score is designed for partial queries:
    # known semantic constraints are stronger than visual/feature-space similarity.
    compatibility = (
        0.35 * room_score
        + 0.20 * adjacency_score
        + 0.15 * relation_score
        + 0.15 * grid_score
        + 0.10 * size_score
        + 0.05 * faiss_similarity
    )

    hard_constraints = (
        room_score >= 0.999
        and size_score > 0.0
        and adjacency_score >= 0.5
    )

    return {
        "compatibility_score": float(compatibility),
        "room_coverage": float(room_score),
        "adjacency_coverage": float(adjacency_score),
        "relation_coverage": float(relation_score),
        "grid_coverage": float(grid_score),
        "size_compatibility": float(size_score),
        "faiss_similarity": float(faiss_similarity),
        "hard_constraints_satisfied": float(1.0 if hard_constraints else 0.0),
    }


def retrieve_partial_query(
    paths: Paths,
    query_id: str,
    visible_room_ids: Set[int],
    removed_room_ids: Set[int],
    candidate_pool: int,
    top_k: int,
) -> Dict[str, Any]:
    """Retrieve complete layouts compatible with one partial query."""
    index, _, ids = load_index(paths)

    query_layout_path = paths.layouts_dir / f"{query_id}.json"
    query_graph_path = paths.graphs_dir / f"{query_id}.json"

    if not query_layout_path.exists() or not query_graph_path.exists():
        raise FileNotFoundError(f"Missing query layout/graph for id: {query_id}")

    query_layout = load_json(query_layout_path)
    query_graph = load_json(query_graph_path)

    query_vector = build_layout_feature(query_layout, query_graph, room_ids=visible_room_ids)
    query_vector = l2_normalize(query_vector.reshape(1, -1))

    pool_size = min(candidate_pool, len(ids))
    distances, indices = index.search(query_vector, pool_size)

    candidate_results = []

    for faiss_score, candidate_index in zip(distances[0], indices[0]):
        if candidate_index < 0:
            continue

        candidate_id = ids[int(candidate_index)]

        candidate_layout_path = paths.layouts_dir / f"{candidate_id}.json"
        candidate_graph_path = paths.graphs_dir / f"{candidate_id}.json"

        if not candidate_layout_path.exists() or not candidate_graph_path.exists():
            continue

        candidate_layout = load_json(candidate_layout_path)
        candidate_graph = load_json(candidate_graph_path)

        metrics = compute_candidate_compatibility(
            query_layout=query_layout,
            query_graph=query_graph,
            candidate_layout=candidate_layout,
            candidate_graph=candidate_graph,
            visible_room_ids=visible_room_ids,
            faiss_similarity=float(faiss_score),
        )

        candidate_results.append({
            "id": candidate_id,
            **metrics,
            "retrieved_original": candidate_id == query_id,
        })

    candidate_results.sort(
        key=lambda item: (
            item["compatibility_score"],
            item["room_coverage"],
            item["adjacency_coverage"],
            item["faiss_similarity"],
        ),
        reverse=True,
    )

    top_results = candidate_results[:top_k]

    for rank, result in enumerate(top_results, start=1):
        result["rank"] = rank

    original_rank = None
    for rank, result in enumerate(candidate_results, start=1):
        if result["id"] == query_id:
            original_rank = rank
            break

    output = {
        "query_id": query_id,
        "visible_room_ids": sorted(visible_room_ids),
        "removed_room_ids": sorted(removed_room_ids),
        "num_visible_rooms": len(visible_room_ids),
        "num_removed_rooms": len(removed_room_ids),
        "candidate_pool": candidate_pool,
        "top_k": top_k,
        "original_rank_in_candidate_pool": original_rank,
        "original_recovered_at_k": bool(original_rank is not None and original_rank <= top_k),
        "results": top_results,
    }

    return output


def draw_boundary(ax: Any, layout: Dict[str, Any]) -> None:
    """Draw the outer building boundary."""
    boundary = layout.get("boundary")

    if not boundary:
        return

    points = [[p[0], p[1]] for p in boundary if isinstance(p, list) and len(p) >= 2]

    if len(points) >= 3:
        patch = Polygon(
            points,
            closed=True,
            facecolor="none",
            edgecolor="black",
            linewidth=2.0,
        )
        ax.add_patch(patch)


def draw_room(
    ax: Any,
    room: Dict[str, Any],
    visible: bool = True,
    removed: bool = False,
    show_text: bool = True,
) -> None:
    """Draw one room polygon or bounding box."""
    room_type_name = get_room_type_name(room)
    color = ROOM_COLORS.get(room_type_name, ROOM_COLORS["Unknown"])

    alpha = 0.85 if visible else 0.15
    edgecolor = "black" if visible else "gray"
    linestyle = "--" if removed else "-"

    points = polygon_points(room)

    if points is not None:
        patch = Polygon(
            points,
            closed=True,
            facecolor=color,
            edgecolor=edgecolor,
            linewidth=1.2,
            linestyle=linestyle,
            alpha=alpha,
        )
        ax.add_patch(patch)
    else:
        x0, y0, x1, y1 = room["bbox"]
        patch = Rectangle(
            (x0, y0),
            x1 - x0,
            y1 - y0,
            facecolor=color,
            edgecolor=edgecolor,
            linewidth=1.2,
            linestyle=linestyle,
            alpha=alpha,
        )
        ax.add_patch(patch)

    if show_text and visible:
        cx, cy = room_centroid(room)
        ax.text(
            cx,
            cy,
            f"{room['id']}\n{room_type_name}",
            ha="center",
            va="center",
            fontsize=5,
        )


def draw_partial_query(ax: Any, layout: Dict[str, Any], visible_room_ids: Set[int], removed_room_ids: Set[int]) -> None:
    """Draw a partial query with removed rooms faded out."""
    for room in layout["rooms"]:
        room_id = int(room["id"])
        draw_room(
            ax,
            room,
            visible=room_id in visible_room_ids,
            removed=room_id in removed_room_ids,
            show_text=True,
        )

    draw_boundary(ax, layout)
    ax.set_xlim(0, 256)
    ax.set_ylim(256, 0)
    ax.set_aspect("equal")
    ax.axis("off")


def draw_snapshot_or_layout(ax: Any, paths: Paths, layout_id: str) -> None:
    """Draw the original snapshot when available; otherwise draw the layout geometry."""
    snapshot_path = paths.snapshots_dir / f"{layout_id}.png"

    if snapshot_path.exists():
        img = Image.open(snapshot_path).convert("RGB")
        ax.imshow(img)
        ax.axis("off")
        return

    layout_path = paths.layouts_dir / f"{layout_id}.json"
    if not layout_path.exists():
        ax.text(0.5, 0.5, f"Missing layout\n{layout_id}", ha="center", va="center")
        ax.axis("off")
        return

    layout = load_json(layout_path)
    for room in layout["rooms"]:
        draw_room(ax, room, visible=True, show_text=False)

    draw_boundary(ax, layout)
    ax.set_xlim(0, 256)
    ax.set_ylim(256, 0)
    ax.set_aspect("equal")
    ax.axis("off")


def draw_result_grid(paths: Paths, result: Dict[str, Any]) -> None:
    """Create a visualization with the partial query and the top-k retrieved layouts."""
    query_id = result["query_id"]
    query_layout = load_json(paths.layouts_dir / f"{query_id}.json")

    visible_room_ids = set(int(x) for x in result["visible_room_ids"])
    removed_room_ids = set(int(x) for x in result["removed_room_ids"])

    items = [{"id": query_id, "label": "Partial query", "is_query": True}]

    for item in result["results"]:
        items.append({
            "id": item["id"],
            "label": (
                f"Top {item['rank']}\n"
                f"score={item['compatibility_score']:.3f}\n"
                f"orig={item['retrieved_original']}"
            ),
            "is_query": False,
        })

    cols = 4
    rows = int(math.ceil(len(items) / cols))

    fig, axes = plt.subplots(rows, cols, figsize=(4.0 * cols, 4.0 * rows))
    axes = np.array(axes).reshape(-1)

    for ax, item in zip(axes, items):
        if item["is_query"]:
            draw_partial_query(ax, query_layout, visible_room_ids, removed_room_ids)
        else:
            draw_snapshot_or_layout(ax, paths, item["id"])

        ax.set_title(f"{item['label']}\nID: {item['id']}", fontsize=9)

    for ax in axes[len(items):]:
        ax.axis("off")

    plt.tight_layout()
    output_path = paths.previews_dir / f"{query_id}_partial_top{result['top_k']}.png"
    plt.savefig(output_path, dpi=200)
    plt.close(fig)


def summarize_results(results: List[Dict[str, Any]], output_root: Path) -> None:
    """Write aggregate CSV, JSON, and Markdown summaries."""
    per_result_rows = []
    per_query_rows = []

    for result in results:
        query_id = result["query_id"]

        for item in result["results"]:
            row = {
                "query_id": query_id,
                "rank": item["rank"],
                "candidate_id": item["id"],
                "retrieved_original": int(bool(item["retrieved_original"])),
                "original_recovered_at_k": int(bool(result["original_recovered_at_k"])),
                "original_rank_in_candidate_pool": result["original_rank_in_candidate_pool"],
                "num_visible_rooms": result["num_visible_rooms"],
                "num_removed_rooms": result["num_removed_rooms"],
                **{
                    key: value
                    for key, value in item.items()
                    if key not in {"id", "rank", "retrieved_original"}
                },
            }
            per_result_rows.append(row)

        scores = [float(item["compatibility_score"]) for item in result["results"]]
        hard = [float(item["hard_constraints_satisfied"]) for item in result["results"]]

        per_query_rows.append({
            "query_id": query_id,
            "num_visible_rooms": result["num_visible_rooms"],
            "num_removed_rooms": result["num_removed_rooms"],
            "original_recovered_at_k": int(bool(result["original_recovered_at_k"])),
            "original_rank_in_candidate_pool": result["original_rank_in_candidate_pool"],
            "mean_topk_compatibility": float(np.mean(scores)) if scores else float("nan"),
            "top1_compatibility": scores[0] if scores else float("nan"),
            "hard_constraint_rate_topk": float(np.mean(hard)) if hard else float("nan"),
        })

    write_csv(output_root / "partial_metrics_per_result.csv", per_result_rows)
    write_csv(output_root / "partial_metrics_by_query.csv", per_query_rows)

    recovered = [row["original_recovered_at_k"] for row in per_query_rows]
    mean_topk = [row["mean_topk_compatibility"] for row in per_query_rows]
    top1 = [row["top1_compatibility"] for row in per_query_rows]
    hard = [row["hard_constraint_rate_topk"] for row in per_query_rows]

    summary = {
        "num_queries": len(per_query_rows),
        "original_recall_at_k": float(np.mean(recovered)) if recovered else float("nan"),
        "mean_topk_compatibility": float(np.mean(mean_topk)) if mean_topk else float("nan"),
        "mean_top1_compatibility": float(np.mean(top1)) if top1 else float("nan"),
        "mean_hard_constraint_rate_topk": float(np.mean(hard)) if hard else float("nan"),
    }

    write_json(output_root / "partial_summary.json", summary)

    lines = []
    lines.append("# Partial Layout Retrieval Summary")
    lines.append("")
    lines.append("This report evaluates retrieval from incomplete floorplan queries.")
    lines.append("")
    lines.append("## Aggregate Metrics")
    lines.append("")
    lines.append(f"- Number of queries: `{summary['num_queries']}`")
    lines.append(f"- Original recall@K: `{summary['original_recall_at_k']:.4f}`")
    lines.append(f"- Mean top-K compatibility: `{summary['mean_topk_compatibility']:.4f}`")
    lines.append(f"- Mean top-1 compatibility: `{summary['mean_top1_compatibility']:.4f}`")
    lines.append(f"- Mean hard-constraint rate@K: `{summary['mean_hard_constraint_rate_topk']:.4f}`")
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    lines.append("- The original complete layout is used as a proxy ground-truth completion.")
    lines.append("- Compatibility is computed from known room types, known semantic adjacencies, spatial relations, grid locations, and candidate size.")
    lines.append("- A high recall@K means that the system can recover the original complete layout from its partial version.")
    lines.append("- A high compatibility score means that retrieved layouts satisfy the visible partial constraints.")
    lines.append("")

    (output_root / "partial_summary.md").write_text("\n".join(lines), encoding="utf-8")

    make_summary_plot(output_root, summary)


def make_summary_plot(output_root: Path, summary: Dict[str, Any]) -> None:
    """Create a compact bar plot for aggregate partial retrieval metrics."""
    labels = [
        "Original\nRecall@K",
        "Top-K\nCompatibility",
        "Top-1\nCompatibility",
        "Hard\nConstraints",
    ]
    values = [
        summary["original_recall_at_k"],
        summary["mean_topk_compatibility"],
        summary["mean_top1_compatibility"],
        summary["mean_hard_constraint_rate_topk"],
    ]

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.bar(labels, values)
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("Score")
    ax.set_title("Partial Layout Retrieval Summary")
    ax.grid(axis="y", alpha=0.3)

    for i, value in enumerate(values):
        ax.text(i, value + 0.02, f"{value:.3f}", ha="center", va="bottom", fontsize=9)

    plt.tight_layout()
    plt.savefig(output_root / "partial_summary_bar.png", dpi=200)
    plt.close(fig)


def select_query_ids(paths: Paths, num_queries: int, seed: int, max_items: Optional[int]) -> List[str]:
    """Select random query ids from available graphs."""
    graph_paths = sorted(paths.graphs_dir.glob("*.json"))

    if max_items is not None:
        graph_paths = graph_paths[:max_items]

    ids = [path.stem for path in graph_paths]
    rng = random.Random(seed)

    if num_queries >= len(ids):
        return ids

    return rng.sample(ids, num_queries)


def main() -> None:
    parser = argparse.ArgumentParser(description="Run partial layout retrieval experiments.")
    parser.add_argument(
        "--processed-root",
        type=Path,
        default=Path("data/processed/rplan"),
        help="Root directory containing layouts_json and graphs_json.",
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=Path("data/raw/rplan/extracted"),
        help="Root directory of the extracted raw RPLAN/Graph2Plan dataset.",
    )
    parser.add_argument(
        "--outputs-root",
        type=Path,
        default=Path("outputs/partial_layout_retrieval"),
        help="Directory where partial retrieval outputs are written.",
    )
    parser.add_argument("--build", action="store_true", help="Build the full-layout FAISS index.")
    parser.add_argument("--clean", action="store_true", help="Clean output directories before running.")
    parser.add_argument("--max-items", type=int, default=None, help="Optional subset size for fast debugging.")
    parser.add_argument("--num-queries", type=int, default=20, help="Number of random partial queries.")
    parser.add_argument("--query-id", type=str, default=None, help="Run one specific query id.")
    parser.add_argument("--top-k", type=int, default=10, help="Number of final retrieved layouts.")
    parser.add_argument("--candidate-pool", type=int, default=200, help="Number of FAISS candidates before re-ranking.")
    parser.add_argument(
        "--mask-strategy",
        type=str,
        default="random",
        choices=["random", "remove_type", "remove_bedroom", "remove_smallest", "remove_largest"],
        help="Strategy used to remove rooms from the query.",
    )
    parser.add_argument("--remove-ratio", type=float, default=0.3, help="Fraction of rooms removed for random masking.")
    parser.add_argument("--remove-type", type=int, default=None, help="Room type id removed when using remove_type.")
    parser.add_argument("--seed", type=int, default=42, help="Random seed.")
    parser.add_argument("--preview-limit", type=int, default=20, help="Maximum number of preview grids to generate.")
    args = parser.parse_args()

    paths = resolve_paths(
        processed_root=args.processed_root,
        outputs_root=args.outputs_root,
        dataset_root=args.dataset_root,
    )

    ensure_clean_dir(paths.outputs_root, clean=args.clean)
    ensure_clean_dir(paths.results_dir, clean=args.clean)
    ensure_clean_dir(paths.previews_dir, clean=args.clean)

    if args.build:
        build_index(paths, max_items=args.max_items)

    rng = random.Random(args.seed)

    if args.query_id is not None:
        query_ids = [args.query_id]
    else:
        query_ids = select_query_ids(
            paths=paths,
            num_queries=args.num_queries,
            seed=args.seed,
            max_items=args.max_items,
        )

    all_results: List[Dict[str, Any]] = []

    print(f"Running partial retrieval for {len(query_ids)} queries...")

    for i, query_id in enumerate(query_ids, start=1):
        query_layout = load_json(paths.layouts_dir / f"{query_id}.json")

        visible_room_ids, removed_room_ids = choose_visible_rooms(
            layout=query_layout,
            strategy=args.mask_strategy,
            remove_ratio=args.remove_ratio,
            remove_type=args.remove_type,
            rng=rng,
        )

        result = retrieve_partial_query(
            paths=paths,
            query_id=query_id,
            visible_room_ids=visible_room_ids,
            removed_room_ids=removed_room_ids,
            candidate_pool=args.candidate_pool,
            top_k=args.top_k,
        )

        all_results.append(result)

        result_path = paths.results_dir / f"{query_id}_partial_top{args.top_k}.json"
        write_json(result_path, result)

        if i <= args.preview_limit:
            draw_result_grid(paths, result)

        print(
            f"[{i}/{len(query_ids)}] query={query_id} "
            f"original_recovered@{args.top_k}={result['original_recovered_at_k']} "
            f"original_rank={result['original_rank_in_candidate_pool']}"
        )

    summarize_results(all_results, paths.outputs_root)

    metadata = {
        "processed_root": str(args.processed_root),
        "dataset_root": str(args.dataset_root),
        "outputs_root": str(args.outputs_root),
        "num_queries": len(query_ids),
        "top_k": args.top_k,
        "candidate_pool": args.candidate_pool,
        "mask_strategy": args.mask_strategy,
        "remove_ratio": args.remove_ratio,
        "remove_type": args.remove_type,
        "seed": args.seed,
    }
    write_json(paths.outputs_root / "partial_run_metadata.json", metadata)

    print("")
    print("Partial layout retrieval completed.")
    print(f"Results: {paths.results_dir}")
    print(f"Previews: {paths.previews_dir}")
    print(f"Summary: {paths.outputs_root / 'partial_summary.md'}")


if __name__ == "__main__":
    main()
