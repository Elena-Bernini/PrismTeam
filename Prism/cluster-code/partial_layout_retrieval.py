#!/usr/bin/env python3
"""
Partial Layout Retrieval.

This script evaluates whether a retrieval system can recover complete floorplans
compatible with incomplete floorplan queries.

It uses the outputs generated by preprocessing.py:
  - data/processed/rplan/layouts_json/
  - data/processed/rplan/graphs_json/

The script creates partial queries by masking rooms from complete layouts, then
retrieves complete layouts that satisfy the remaining semantic and topological
constraints.

The retrieval strategy is intentionally interpretable:
  1. build a lightweight full-layout index with FAISS;
  2. generate partial query descriptors;
  3. retrieve a candidate pool;
  4. re-rank candidates using explicit compatibility metrics.

Example:
    python cluster-code/partial_layout_retrieval.py \
        --processed-root data/processed/rplan \
        --outputs-root outputs/partial_layout_retrieval \
        --build \
        --clean \
        --num-queries 20 \
        --mask-strategy random \
        --remove-ratio 0.3 \
        --candidate-pool 200 \
        --top-k 10
"""

